// ------------------------------------------------------------- dump impl ----

std::string dump_config_yaml(const RwConfig& cfg) {
    std::ostringstream o;
    o << "# Auto-generated by raidwatch (no config.yaml.example present).\n";
    o << "processes:\n";
    o << "  spt_server_process_name: " << yq(cfg.processes.spt_server_process_name) << "\n";
    o << "  headless_process_name: " << yq(cfg.processes.headless_process_name) << "\n";
    o << "  headless_cmdline_pattern: " << yq(cfg.processes.headless_cmdline_pattern) << "\n";

    o << "collection:\n";
    o << "  interval_seconds: " << cfg.collection.interval_seconds << "\n";
    o << "  history_retention_hours: " << cfg.collection.history_retention_hours << "\n";
    o << "  whea_poll_seconds: " << cfg.collection.whea_poll_seconds << "\n";
    o << "  top_others_poll_seconds: " << cfg.collection.top_others_poll_seconds << "\n";

    o << "temps:\n";
    o << "  lhm_dll_path: " << yq(cfg.temps.lhm_dll_path) << "\n";
    o << "  cpu_sensor_name: " << yq(cfg.temps.cpu_sensor_name) << "\n";
    o << "  tctl_offset: " << cfg.temps.tctl_offset << "\n";

    o << "fika:\n";
    o << "  spt_path: " << yq(cfg.fika.spt_path) << "\n";
    o << "  raid_udp_port: " << cfg.fika.raid_udp_port << "\n";
    o << "  headless_path: " << yq(cfg.fika.headless_path) << "\n";
    if (cfg.fika.log_paths.empty()) {
        o << "  log_paths: {}\n";
    } else {
        o << "  log_paths:\n";
        for (const auto& [k, v] : cfg.fika.log_paths) o << "    " << k << ": " << yq(v) << "\n";
    }
    if (cfg.fika.risky_mod_names.empty()) {
        o << "  risky_mod_names: []\n";
    } else {
        o << "  risky_mod_names:\n";
        for (const auto& m : cfg.fika.risky_mod_names) o << "    - " << yq(m) << "\n";
    }

    if (cfg.gates.empty()) {
        o << "gates: {}\n";
    } else {
        o << "gates:\n";
        for (const auto& [id, g] : cfg.gates) {
            o << "  " << id << ":\n";
            o << "    enabled: " << (g.enabled ? "true" : "false") << "\n";
            o << "    threshold: " << g.threshold << "\n";
            o << "    operator: " << yq(g.op) << "\n";
            o << "    duration_seconds: " << g.duration_seconds << "\n";
            o << "    severity: " << yq(g.severity) << "\n";
            o << "    recommendation: " << yq(g.recommendation) << "\n";
            o << "    metric: " << yq(g.metric) << "\n";
        }
    }
    return o.str();
}

