// ------------------------------------------------------- section parsers ----

void parse_processes(ry::ConstNodeRef& n, RwConfig& cfg,
                     std::vector<std::string>* unk) {
    for (auto f : n.children()) {
        auto k = str(f.key());
        if (k == "spt_server_process_name") cfg.processes.spt_server_process_name = str(f.val());
        else if (k == "headless_process_name") cfg.processes.headless_process_name = str(f.val());
        else if (k == "headless_cmdline_pattern") cfg.processes.headless_cmdline_pattern = str(f.val());
        else warn(unk, "unknown key under 'processes': " + k);
    }
}

void parse_collection(ry::ConstNodeRef& n, RwConfig& cfg,
                      std::vector<std::string>* unk) {
    for (auto f : n.children()) {
        auto k = str(f.key());
        if (k == "interval_seconds") cfg.collection.interval_seconds = to_double(f.val(), "collection.interval_seconds");
        else if (k == "history_retention_hours") cfg.collection.history_retention_hours = static_cast<int>(to_int(f.val(), "collection.history_retention_hours"));
        else if (k == "whea_poll_seconds") cfg.collection.whea_poll_seconds = to_double(f.val(), "collection.whea_poll_seconds");
        else if (k == "top_others_poll_seconds") cfg.collection.top_others_poll_seconds = to_double(f.val(), "collection.top_others_poll_seconds");
        else warn(unk, "unknown key under 'collection': " + k);
    }
    if (cfg.collection.interval_seconds <= 0.0)
        throw RwConfigError("collection.interval_seconds must be > 0");
}

void parse_temps(ry::ConstNodeRef& n, RwConfig& cfg, std::vector<std::string>* unk) {
    for (auto f : n.children()) {
        auto k = str(f.key());
        if (k == "lhm_dll_path") cfg.temps.lhm_dll_path = str(f.val());
        else if (k == "cpu_sensor_name") cfg.temps.cpu_sensor_name = str(f.val());
        else if (k == "tctl_offset") cfg.temps.tctl_offset = to_double(f.val(), "temps.tctl_offset");
        else warn(unk, "unknown key under 'temps': " + k);
    }
}

void parse_fika(ry::ConstNodeRef& n, RwConfig& cfg, std::vector<std::string>* unk) {
    for (auto f : n.children()) {
        auto k = str(f.key());
        if (k == "spt_path") cfg.fika.spt_path = str(f.val());
        else if (k == "headless_path") cfg.fika.headless_path = str(f.val());
        else if (k == "raid_udp_port") cfg.fika.raid_udp_port = static_cast<int>(to_int(f.val(), "fika.raid_udp_port"));
        else if (k == "log_paths") {
            if (!f.is_map()) throw RwConfigError("fika.log_paths must be a mapping");
            for (auto lp : f.children()) cfg.fika.log_paths[str(lp.key())] = str(lp.val());
        } else if (k == "risky_mod_names") {
            if (!f.is_seq()) throw RwConfigError("fika.risky_mod_names must be a sequence");
            for (auto m : f.children()) cfg.fika.risky_mod_names.push_back(str(m.val()));
        } else {
            warn(unk, "unknown key under 'fika': " + k);
        }
    }
    if (cfg.fika.raid_udp_port < 1 || cfg.fika.raid_udp_port > 65535)
        throw RwConfigError("fika.raid_udp_port must be 1-65535");
}

void parse_gate(const std::string& id, ry::ConstNodeRef& n, RwConfig& cfg,
                std::vector<std::string>* unk) {
    GateCfg g;
    for (auto f : n.children()) {
        auto k = str(f.key());
        if (k == "enabled") g.enabled = to_bool(f.val(), "gate." + id + ".enabled");
        else if (k == "threshold") g.threshold = to_double(f.val(), "gate." + id + ".threshold");
        else if (k == "operator") g.op = str(f.val());
        else if (k == "duration_seconds") g.duration_seconds = to_double(f.val(), "gate." + id + ".duration_seconds");
        else if (k == "severity") g.severity = str(f.val());
        else if (k == "recommendation") g.recommendation = str(f.val());
        else if (k == "metric") g.metric = str(f.val());
        else warn(unk, "unknown key under gate '" + id + "': " + k);
    }
    // Validations (real config mistakes — hard errors, D4).
    if (!operator_is_valid(g.op))
        throw RwConfigError("gate '" + id + "' operator must be one of > < >= <= == !=, got '" + g.op + "'");
    std::string sev_l = g.severity;
    std::transform(sev_l.begin(), sev_l.end(), sev_l.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    if (!severity_is_valid(sev_l))
        throw RwConfigError("gate '" + id + "' severity must be one of low medium high, got '" + g.severity + "'");
    g.severity = sev_l;
    if (g.duration_seconds < 0.0)
        throw RwConfigError("gate '" + id + "' duration_seconds must be >= 0");
    cfg.gates[id] = g;
}

void parse_gates(ry::ConstNodeRef& n, RwConfig& cfg, std::vector<std::string>* unk) {
    for (auto g : n.children()) parse_gate(str(g.key()), g, cfg, unk);
}

