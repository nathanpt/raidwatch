RwConfig load_config(const std::string& config_path, const std::string& example_path,
                     std::vector<std::string>* unknown_keys_out) {
    // --- D23: first-run auto-generation ---
    if (!fs::exists(config_path)) {
        std::error_code ec;
        fs::create_directories(fs::path(config_path).parent_path(), ec);
        if (fs::exists(example_path)) {
            fs::copy_file(example_path, config_path, fs::copy_options::overwrite_existing, ec);
            if (ec) throw RwConfigError("auto-generate: copy failed: " + ec.message());
            std::fprintf(stderr, "[rw_config] auto-generated %s from %s\n",
                         config_path.c_str(), example_path.c_str());
        } else {
            std::ofstream out(config_path, std::ios::binary);
            if (!out) throw RwConfigError("auto-generate: cannot write " + config_path);
            out << dump_config_yaml(RwConfig{});
            std::fprintf(stderr, "[rw_config] auto-generated %s (no example present)\n",
                         config_path.c_str());
        }
    }

    // --- read + parse ---
    std::ifstream in(config_path, std::ios::binary);
    if (!in) throw RwConfigError("cannot read config: " + config_path);
    std::string buf((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());

    ry::Tree tree;
    try {
        tree = ry::parse_in_arena(ry::to_csubstr(buf));
    } catch (const std::exception& e) {
        throw RwConfigError(std::string("YAML parse error: ") + e.what());
    }

    RwConfig cfg;
    ry::ConstNodeRef root = tree.rootref();
    if (!root.is_map()) {
        // Empty / non-mapping document ⇒ safe defaults (config.py: raw == {}).
        return cfg;
    }

    for (auto sec : root.children()) {
        auto k = str(sec.key());
        if (k == "processes") { if (!sec.is_map()) throw RwConfigError("'processes' must be a mapping"); parse_processes(sec, cfg, unknown_keys_out); }
        else if (k == "collection") { if (!sec.is_map()) throw RwConfigError("'collection' must be a mapping"); parse_collection(sec, cfg, unknown_keys_out); }
        else if (k == "temps") { if (!sec.is_map()) throw RwConfigError("'temps' must be a mapping"); parse_temps(sec, cfg, unknown_keys_out); }
        else if (k == "fika") { if (!sec.is_map()) throw RwConfigError("'fika' must be a mapping"); parse_fika(sec, cfg, unknown_keys_out); }
        else if (k == "gates") { if (!sec.is_map()) throw RwConfigError("'gates' must be a mapping"); parse_gates(sec, cfg, unknown_keys_out); }
        else {
            // Dropped HTTP sections are silently tolerated too (warn, never fail).
            warn(unknown_keys_out, "unknown top-level key (ignored): " + k);
        }
    }
    return cfg;
}

