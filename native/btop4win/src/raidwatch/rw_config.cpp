[[nodiscard]] std::string str(ry::csubstr s) { return {s.data(), s.size()}; }

// Emit a warning to stderr (the TUI/service has no logger yet) and optionally
// record it for the caller's testability.
void warn(std::vector<std::string>* sink, const std::string& msg) {
    std::fprintf(stderr, "[rw_config] WARNING: %s\n", msg.c_str());
    if (sink) sink->push_back(msg);
}

bool operator_is_valid(const std::string& op) {
    for (const char* v : kValidOperators)
        if (op == v) return true;
    return false;
}

bool severity_is_valid(const std::string& sev) {
    for (const char* v : kValidSeverities)
        if (sev == v) return true;
    return false;
}

// --- scalar coercion (throw on type mismatch — real config mistakes) -------

[[nodiscard]] bool to_bool(ry::csubstr s, const std::string& ctx) {
    auto v = str(s);
    if (v == "true" || v == "True" || v == "TRUE" || v == "yes") return true;
    if (v == "false" || v == "False" || v == "FALSE" || v == "no") return false;
    throw RwConfigError(ctx + ": expected bool, got '" + v + "'");
}

[[nodiscard]] long long to_int(ry::csubstr s, const std::string& ctx) {
    auto v = str(s);
    // ryml may mark ints; we still parse defensively.
    try {
        size_t pos = 0;
        long long out = std::stoll(v, &pos);
        if (pos != v.size()) throw 0;
        return out;
    } catch (...) {
        throw RwConfigError(ctx + ": expected integer, got '" + v + "'");
    }
}

[[nodiscard]] double to_double(ry::csubstr s, const std::string& ctx) {
    auto v = str(s);
    try {
        size_t pos = 0;
        double out = std::stod(v, &pos);
        if (pos != v.size()) throw 0;
        return out;
    } catch (...) {
        throw RwConfigError(ctx + ": expected number, got '" + v + "'");
    }
}


// ----------------------------------------------------------------- dump -----

// Quote a string scalar for YAML output. Always double-quoted (simplest way to
// be correct for Windows paths, regex, free text); escape backslash + quote.
std::string yq(const std::string& v) {
    std::string out;
    out.reserve(v.size() + 2);
    out += '"';
    for (char c : v) {
        if (c == '\\' || c == '"') out += '\\';
        out += c;
    }
    out += '"';
    return out;
}

